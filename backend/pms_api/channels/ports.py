"""The channel operations required by booking and ARI use cases."""

from typing import Any, Protocol


class ChannelAdapter(Protocol):
    def property(self, property_id: str) -> dict: ...
    def catalog(self, resource: str, property_id: str) -> list[dict]: ...
    def revision(self, revision_id: str) -> dict: ...
    def feed(self, property_id: str) -> list[dict]: ...
    def ack(self, revision_id: str) -> None: ...
    def push_availability(self, values: list[dict]) -> None: ...
    def push_restrictions(self, values: list[dict]) -> None: ...
    def setup_webhook(self, property_id: str, callback_url: str, webhook_secret: str) -> str: ...


class RevisionRepository(Protocol):
    def has_revision(self, tenant_id: str, revision_id: str) -> bool: ...
    def enqueue_ack(self, tenant_id: str, actor_id: str, revision_id: str) -> Any: ...
