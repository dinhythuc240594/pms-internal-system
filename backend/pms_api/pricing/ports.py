"""Storage operations required by pricing, independent of the SQL implementation."""

from collections.abc import Iterable
from typing import Any, Protocol


class PricingRepository(Protocol):
    def tenant(self, tenant_id) -> Any: ...
    def exchange_rate(self, tenant_id, currency, base) -> Any: ...
    def rules(self, tenant_id) -> list: ...
    def voucher_by_code(self, tenant_id, code, *, locked=False) -> Any: ...
    def promotions(self, tenant_id) -> Iterable: ...
    def voucher_by_id(self, tenant_id, voucher_id) -> Any: ...
    def add_redemption(self, tenant_id, voucher_id, reservation_id, discount) -> None: ...
